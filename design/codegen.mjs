#!/usr/bin/env node
// Generates the icon-key contract for web (TS), iOS (Swift) and Android (Kotlin)
// from design/icons.json, the single source of truth for every icon key the
// backend sends (docs/DESIGN_LANGUAGE.md §1 and §6). Apps never hard-code a key
// list: they decode the server's `icon` string through the generated
// `AppIcon` type, which falls back to a neutral symbol for unknown keys.
//
//   node design/codegen.mjs            write all targets
//   node design/codegen.mjs --check    exit 1 if any target is stale (CI)
//   node design/codegen.mjs --only web write one target (web|ios|android)
//
// Mobile repos default to the 1.2.0 worktrees next to FitCircleBE
// (FitCircle-iOS-onboarding, Fitcircle-Android-onboarding); override with
// IOS_REPO (the repo root) / ANDROID_REPO (the `com/fitcircle/app/` source
// directory). A missing target directory is skipped with a warning so web CI
// works on its own.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const beRoot = resolve(here, '..');
const registry = JSON.parse(readFileSync(resolve(here, 'icons.json'), 'utf8'));

const args = process.argv.slice(2);
const check = args.includes('--check');
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;

const IOS_REPO = process.env.IOS_REPO ?? resolve(beRoot, '../FitCircle-iOS-onboarding');
const ANDROID_REPO =
  process.env.ANDROID_REPO ?? resolve(beRoot, '../Fitcircle-Android-onboarding/FitCircle/app/src/main/java/com/fitcircle/app/');

const targets = {
  web: { root: beRoot, path: resolve(beRoot, 'apps/web/app/lib/design/icons.generated.ts') },
  ios: { root: IOS_REPO, path: resolve(IOS_REPO, 'FitCircle/DesignSystem/AppIcon.generated.swift') },
  android: { root: ANDROID_REPO, path: resolve(ANDROID_REPO, 'core/design/AppIcon.generated.kt') },
};

// ---------------------------------------------------------------- validation

const fail = (msg) => {
  console.error(`design/icons.json: ${msg}`);
  process.exit(1);
};
const icons = Object.entries(registry.icons ?? {});
if (!icons.length) fail('no icons');
if (!registry.icons[registry.fallback]) fail(`fallback "${registry.fallback}" is not a key`);
const normEmoji = (e) => e.replace(/️/g, '');
const aliasOwner = new Map();
for (const [key, v] of icons) {
  if (!/^[a-z][a-z0-9_]*$/.test(key)) fail(`bad key "${key}" (snake_case)`);
  for (const f of ['label', 'ios', 'android', 'web']) if (typeof v[f] !== 'string' || !v[f].trim()) fail(`${key}.${f} missing`);
  if (!/^[a-z0-9]+(\.[a-z0-9]+)*$/.test(v.ios)) fail(`${key}.ios "${v.ios}" is not an SF Symbol name`);
  if (!/^[a-z0-9_]+$/.test(v.android)) fail(`${key}.android "${v.android}" is not a Material Symbols name`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(v.web)) fail(`${key}.web "${v.web}" is not a lucide name`);
  if (!Array.isArray(v.emoji)) fail(`${key}.emoji must be an array`);
  for (const e of v.emoji) {
    const n = normEmoji(e);
    if (aliasOwner.has(n)) fail(`emoji ${e} is listed under both "${aliasOwner.get(n)}" and "${key}"`);
    aliasOwner.set(n, key);
  }
}

// ---------------------------------------------------------------- naming

const camel = (k) => k.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const SWIFT_RESERVED = new Set(['repeat', 'return', 'switch', 'default', 'do', 'for', 'while', 'if', 'else', 'guard', 'where', 'self', 'super', 'true', 'false', 'nil', 'operator', 'import', 'extension', 'init', 'deinit', 'subscript', 'typealias', 'static', 'throw', 'throws', 'try', 'catch', 'defer', 'break', 'continue', 'fallthrough', 'public', 'private', 'internal', 'case', 'class', 'struct', 'enum', 'protocol', 'func', 'var', 'let', 'in', 'is', 'as', 'none', 'some', 'any']);
const swiftCase = (k) => {
  const c = camel(k);
  return SWIFT_RESERVED.has(c) ? `\`${c}\`` : c;
};
const swiftRef = (k) => camel(k); // `.repeat` needs no backticks after a dot
const constName = (k) => k.toUpperCase();
const q = (s) => JSON.stringify(s);

const header = (c) =>
  `${c} GENERATED by FitCircleBE/design/codegen.mjs from design/icons.json (v${registry.version}).\n${c} Do not edit: change the registry and re-run \`node design/codegen.mjs\`.\n`;

// ---------------------------------------------------------------- TypeScript

function genTs() {
  let o = header('//') + '\n/* eslint-disable */\n\n';
  o += `export const ICON_REGISTRY_VERSION = ${registry.version};\n\n`;
  o += `/** Every icon key the backend may send. */\nexport const ICON_KEYS = [\n${icons.map(([k]) => `  '${k}',`).join('\n')}\n] as const;\nexport type IconKey = (typeof ICON_KEYS)[number];\n\n`;
  o += `/** Neutral symbol apps render for an unknown key. */\nexport const ICON_FALLBACK: IconKey = '${registry.fallback}';\n\n`;
  o += `export interface IconSpec {\n  readonly label: string;\n  /** SF Symbol name (iOS). */\n  readonly ios: string;\n  /** Material Symbols Rounded name (Android). */\n  readonly android: string;\n  /** lucide icon name (web). */\n  readonly web: string;\n}\n\n`;
  o += `export const ICONS: Readonly<Record<IconKey, IconSpec>> = {\n`;
  for (const [k, v] of icons) o += `  ${k}: { label: ${q(v.label)}, ios: ${q(v.ios)}, android: ${q(v.android)}, web: ${q(v.web)} },\n`;
  o += `};\n\n`;
  o += `/** Legacy emoji (U+FE0F removed) → the key that replaces it. */\nexport const EMOJI_TO_ICON: Readonly<Record<string, IconKey>> = {\n`;
  for (const [k, v] of icons) for (const e of v.emoji) o += `  ${q(normEmoji(e))}: '${k}',\n`;
  o += `};\n`;
  return o;
}

// ---------------------------------------------------------------- Swift

function genSwift() {
  let o = header('//') + '\nimport Foundation\n\n';
  o += `/// A server icon key (design/icons.json). Decode the API's \`icon\` string with\n/// \`AppIcon.resolve(_:)\` (or Decodable): unknown keys become \`.fallback\`, so a\n/// newer server key never breaks rendering.\n`;
  o += `enum AppIcon: String, CaseIterable, Sendable {\n`;
  for (const [k] of icons) o += `    case ${swiftCase(k)} = "${k}"\n`;
  o += `\n    static let registryVersion = ${registry.version}\n    static let fallback: AppIcon = .${swiftRef(registry.fallback)}\n\n`;
  o += `    static func resolve(_ key: String?) -> AppIcon {\n        guard let key, let icon = AppIcon(rawValue: key) else { return fallback }\n        return icon\n    }\n\n`;
  o += `    /// SF Symbol name.\n    var sfSymbol: String {\n        switch self {\n`;
  for (const [k, v] of icons) o += `        case .${swiftRef(k)}: return "${v.ios}"\n`;
  o += `        }\n    }\n\n`;
  o += `    /// Short English description (accessibility hint, debug).\n    var label: String {\n        switch self {\n`;
  for (const [k, v] of icons) o += `        case .${swiftRef(k)}: return ${q(v.label)}\n`;
  o += `        }\n    }\n}\n\n`;
  o += `extension AppIcon: Decodable {\n    init(from decoder: Decoder) throws {\n        let container = try decoder.singleValueContainer()\n        self = AppIcon.resolve(try? container.decode(String.self))\n    }\n}\n`;
  return o;
}

// ---------------------------------------------------------------- Kotlin

function genKotlin() {
  let o = header('//') + '\n@file:Suppress("unused")\n\npackage com.fitcircle.app.core.design\n\n';
  o += `/**\n * A server icon key (design/icons.json). Resolve the API's \`icon\` string with\n * [AppIcon.fromKey]: unknown keys become [FALLBACK], so a newer server key never\n * breaks rendering. [materialSymbol] is the Material Symbols Rounded name.\n */\n`;
  o += `enum class AppIcon(val key: String, val materialSymbol: String, val label: String) {\n`;
  o += icons.map(([k, v]) => `    ${constName(k)}(${q(k)}, ${q(v.android)}, ${q(v.label)}),`).join('\n');
  o += `\n    ;\n\n    companion object {\n        const val REGISTRY_VERSION: Int = ${registry.version}\n        val FALLBACK: AppIcon = ${constName(registry.fallback)}\n        private val byKey: Map<String, AppIcon> = entries.associateBy { it.key }\n\n        fun fromKey(key: String?): AppIcon = key?.let { byKey[it] } ?: FALLBACK\n    }\n}\n`;
  return o;
}

// ---------------------------------------------------------------- write / check

const gens = { web: genTs, ios: genSwift, android: genKotlin };
let stale = 0;
for (const [name, { root, path }] of Object.entries(targets)) {
  if (only && only !== name) continue;
  if (!existsSync(root)) {
    console.warn(`skip ${name}: ${root} not found`);
    continue;
  }
  const out = gens[name]();
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== out) {
      console.error(`stale: ${path}`);
      stale++;
    } else console.log(`ok: ${name}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, out);
    console.log(`wrote ${name}: ${path} (${icons.length} icons)`);
  }
}
if (stale) {
  console.error('Run `node design/codegen.mjs` and commit the result.');
  process.exit(1);
}
