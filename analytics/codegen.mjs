#!/usr/bin/env node
// Generates typed analytics event constructors for web (TS), iOS (Swift) and
// Android (Kotlin) from analytics/tracking-plan.json — the single source of
// truth for FitCircle's product analytics. Clients never hand-write event
// names or property keys; they call the generated constructors and hand the
// payload to their provider-agnostic Analytics facade.
//
//   node analytics/codegen.mjs            write all targets
//   node analytics/codegen.mjs --check    exit 1 if any target is stale (CI)
//   node analytics/codegen.mjs --only web write one target (web|ios|android)
//
// Mobile repos are expected as siblings of FitCircleBE (FitCircle-iOS,
// Fitcircle-Android); override with IOS_REPO / ANDROID_REPO. A missing sibling
// is skipped with a warning so web CI works on its own.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const beRoot = resolve(here, '..');
const plan = JSON.parse(readFileSync(resolve(here, 'tracking-plan.json'), 'utf8'));

const args = process.argv.slice(2);
const check = args.includes('--check');
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : null;

const IOS_REPO = process.env.IOS_REPO ?? resolve(beRoot, '../FitCircle-iOS');
const ANDROID_REPO = process.env.ANDROID_REPO ?? resolve(beRoot, '../Fitcircle-Android');

const targets = {
  web: resolve(beRoot, 'apps/web/app/lib/analytics/events.generated.ts'),
  ios: resolve(IOS_REPO, 'FitCircle/Core/Analytics/AnalyticsEvents.generated.swift'),
  android: resolve(ANDROID_REPO, 'FitCircle/app/src/main/java/com/fitcircle/app/core/analytics/AnalyticsEvents.generated.kt'),
};

// ---------------------------------------------------------------- validation

const fail = (msg) => { console.error(`tracking-plan.json: ${msg}`); process.exit(1); };
const seen = new Set();
for (const e of plan.events) {
  if (!/^[A-Z][A-Za-z0-9-]*( [A-Za-z0-9-]+)*$/.test(e.name)) fail(`bad event name "${e.name}"`);
  if (seen.has(e.name)) fail(`duplicate event "${e.name}"`);
  seen.add(e.name);
  for (const p of e.properties) {
    if (!/^[a-z][a-z0-9_]*$/.test(p.name)) fail(`${e.name}: bad property "${p.name}"`);
    if (p.type === 'enum' && !p.enum && !p.values) fail(`${e.name}.${p.name}: enum needs "enum" or "values"`);
    if (p.enum && !plan.enums[p.enum]) fail(`${e.name}.${p.name}: unknown enum "${p.enum}"`);
  }
}

// ---------------------------------------------------------------- naming

const words = (s) => s.replace(/[^A-Za-z0-9]+/g, ' ').trim().split(/\s+/);
const cap = (w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
const capKeep = (w) => (/^[A-Z0-9]+$/.test(w) && w.length <= 3 ? w : cap(w)); // AI, FitCircle-ish
const pascal = (s) => words(s).map((w) => (/^[A-Z][a-z]+[A-Z]/.test(w) ? w : capKeep(w))).join('');
const camel = (s) => { const p = pascal(s); return p.replace(/^[A-Z]+(?=[A-Z][a-z]|$)|^[A-Z]/, (m) => m.toLowerCase()); };
const caseName = (v) => { const c = camel(v); return /^[0-9]/.test(c) ? `band${pascal(v)}` : c; };
const constName = (v) => { const u = v.toUpperCase().replace(/[^A-Z0-9]+/g, '_'); return /^[0-9]/.test(u) ? `BAND_${u}` : u; };

const SWIFT_RESERVED = new Set(['repeat', 'return', 'switch', 'default', 'do', 'for', 'while', 'if', 'else', 'guard', 'where', 'self', 'super', 'true', 'false', 'nil', 'operator', 'import', 'extension', 'init', 'deinit', 'subscript', 'typealias', 'static', 'throw', 'throws', 'try', 'catch', 'defer', 'break', 'continue', 'fallthrough', 'public', 'private', 'default', 'internal', 'case', 'class', 'struct', 'enum', 'protocol', 'func', 'var', 'let', 'in', 'is', 'as', 'none']);
const swiftId = (s) => (SWIFT_RESERVED.has(s) ? `\`${s}\`` : s);

// Every enum type, named or inline, resolved once.
const enumTypes = new Map(); // typeName -> values
for (const [k, values] of Object.entries(plan.enums)) enumTypes.set(pascal(k), values);
const enumTypeFor = (owner, p) => {
  if (p.enum) return pascal(p.enum);
  const name = `${pascal(owner)}${pascal(p.name)}`;
  enumTypes.set(name, p.values);
  return name;
};
const events = plan.events.map((e) => ({
  ...e,
  fn: camel(e.name),
  props: [...e.properties.filter((p) => p.required), ...e.properties.filter((p) => !p.required)]
    .map((p) => ({ ...p, param: camel(p.name.replace(/_/g, ' ')), enumType: p.type === 'enum' ? enumTypeFor(e.name, p) : null })),
}));
const userProps = plan.userProperties.map((p) => ({
  ...p, param: camel(p.name.replace(/_/g, ' ')), enumType: p.type === 'enum' ? enumTypeFor('User', p) : null,
}));

const header = (c) => `${c} GENERATED by FitCircleBE/analytics/codegen.mjs from analytics/tracking-plan.json (v${plan.version}).\n${c} Do not edit: change the plan and re-run \`node analytics/codegen.mjs\`.\n`;

// ---------------------------------------------------------------- TypeScript

function genTs() {
  const tsType = (p) => (p.enumType ? p.enumType : { string: 'string', int: 'number', number: 'number', bool: 'boolean' }[p.type] ?? 'unknown');
  let o = header('//') + '\n/* eslint-disable */\n\n';
  o += `export interface AnalyticsEventPayload {\n  readonly name: AnalyticsEventName;\n  readonly properties: Readonly<Record<string, string | number | boolean>>;\n}\n\n`;
  for (const [t, vals] of enumTypes) o += `export type ${t} = ${vals.map((v) => `'${v}'`).join(' | ')};\n`;
  o += `\nexport const ANALYTICS_EVENT_NAMES = [\n${events.map((e) => `  '${e.name}',`).join('\n')}\n] as const;\nexport type AnalyticsEventName = (typeof ANALYTICS_EVENT_NAMES)[number];\n\n`;
  o += `const clean = (p: Record<string, unknown>) =>\n  Object.fromEntries(Object.entries(p).filter(([, v]) => v !== undefined && v !== null)) as Record<string, string | number | boolean>;\n\n`;
  o += `export const AnalyticsEvents = {\n`;
  for (const e of events) {
    o += `  /** ${e.description} */\n`;
    if (!e.props.length) { o += `  ${e.fn}: (): AnalyticsEventPayload => ({ name: '${e.name}', properties: {} }),\n`; continue; }
    const sig = e.props.map((p) => `${p.name}${p.required ? '' : '?'}: ${tsType(p)}`).join('; ');
    const allOptional = e.props.every((p) => !p.required);
    o += `  ${e.fn}: (p: { ${sig} }${allOptional ? ' = {}' : ''}): AnalyticsEventPayload => ({ name: '${e.name}', properties: clean(p) }),\n`;
  }
  o += `} as const;\n\n`;
  o += `/** Canonical user properties. Keys in USER_PROPERTIES_SET_ONCE must be sent with setOnce. */\nexport interface AnalyticsUserProperties {\n${userProps.map((p) => `  ${p.name}?: ${tsType(p)};`).join('\n')}\n}\n`;
  o += `export const USER_PROPERTIES_SET_ONCE: ReadonlyArray<keyof AnalyticsUserProperties> = [${userProps.filter((p) => p.setOnce).map((p) => `'${p.name}'`).join(', ')}];\n`;
  return o;
}

// ---------------------------------------------------------------- Swift

function genSwift() {
  const swType = (p) => (p.enumType ? p.enumType : { string: 'String', int: 'Int', number: 'Double', bool: 'Bool' }[p.type]);
  const wire = (p, v) => (p.enumType ? `${v}.rawValue` : v);
  let o = header('//') + '\nimport Foundation\n\n';
  o += `/// One analytics event, ready for \`Analytics.track(_:)\`. Build it with \`AnalyticsEvents\`.\nstruct AnalyticsEventPayload {\n    let name: String\n    let properties: [String: Any]\n}\n\n`;
  // Enum types are nested in AnalyticsEvents: top-level names like
  // Environment / Store / MealType would shadow SwiftUI, TCA and app types.
  o += `/// Every canonical event. Names and keys come from tracking-plan.json.\nenum AnalyticsEvents {\n`;
  for (const [t, vals] of enumTypes) {
    o += `    enum ${t}: String, CaseIterable, Sendable {\n${vals.map((v) => `        case ${swiftId(caseName(v))} = "${v}"`).join('\n')}\n    }\n\n`;
  }
  o += `    static let allNames: [String] = [\n${events.map((e) => `        "${e.name}",`).join('\n')}\n    ]\n\n`;
  for (const e of events) {
    const params = e.props.map((p) => `${p.param}: ${swType(p)}${p.required ? '' : '? = nil'}`).join(', ');
    o += `    /// ${e.description}\n    static func ${e.fn}(${params}) -> AnalyticsEventPayload {\n`;
    if (!e.props.length) { o += `        AnalyticsEventPayload(name: "${e.name}", properties: [:])\n    }\n\n`; continue; }
    o += `        var p: [String: Any] = [:]\n`;
    for (const pr of e.props) {
      o += pr.required ? `        p["${pr.name}"] = ${wire(pr, pr.param)}\n` : `        if let ${pr.param} { p["${pr.name}"] = ${wire(pr, pr.param)} }\n`;
    }
    o += `        return AnalyticsEventPayload(name: "${e.name}", properties: p)\n    }\n\n`;
  }
  o += `}\n\n`;
  const swQualified = (p) => (p.enumType ? `AnalyticsEvents.${p.enumType}` : swType(p));
  o += `/// Canonical user properties. \`setOnceKeys\` must be sent with setOnce.\nstruct AnalyticsUserProperties {\n${userProps.map((p) => `    var ${p.param}: ${swQualified(p)}?`).join('\n')}\n\n`;
  o += `    static let setOnceKeys: Set<String> = [${userProps.filter((p) => p.setOnce).map((p) => `"${p.name}"`).join(', ')}]\n\n`;
  o += `    var dictionary: [String: Any] {\n        var p: [String: Any] = [:]\n${userProps.map((p) => `        if let ${p.param} { p["${p.name}"] = ${wire(p, p.param)} }`).join('\n')}\n        return p\n    }\n}\n`;
  return o;
}

// ---------------------------------------------------------------- Kotlin

function genKotlin() {
  const ktType = (p) => (p.enumType ? p.enumType : { string: 'String', int: 'Int', number: 'Double', bool: 'Boolean' }[p.type]);
  const wire = (p, v) => (p.enumType ? `${v}.wire` : v);
  let o = header('//') + '\n@file:Suppress("unused", "MemberVisibilityCanBePrivate")\n\npackage com.fitcircle.app.core.analytics\n\n';
  o += `/** One analytics event, ready for [Analytics.track]. Build it with [AnalyticsEvents]. */\ndata class AnalyticsEventPayload(val name: String, val properties: Map<String, Any>)\n\n`;
  for (const [t, vals] of enumTypes) {
    o += `enum class ${t}(val wire: String) {\n${vals.map((v) => `    ${constName(v)}("${v}"),`).join('\n')}\n}\n\n`;
  }
  o += `/** Every canonical event. Names and keys come from tracking-plan.json. */\nobject AnalyticsEvents {\n    val allNames: List<String> = listOf(\n${events.map((e) => `        "${e.name}",`).join('\n')}\n    )\n\n`;
  for (const e of events) {
    const params = e.props.map((p) => `${p.param}: ${ktType(p)}${p.required ? '' : '? = null'}`).join(', ');
    o += `    /** ${e.description} */\n    fun ${e.fn}(${params}): AnalyticsEventPayload {\n`;
    if (!e.props.length) { o += `        return AnalyticsEventPayload("${e.name}", emptyMap())\n    }\n\n`; continue; }
    o += `        val p = mutableMapOf<String, Any>()\n`;
    for (const pr of e.props) {
      o += pr.required ? `        p["${pr.name}"] = ${wire(pr, pr.param)}\n` : `        ${pr.param}?.let { p["${pr.name}"] = ${wire(pr, 'it')} }\n`;
    }
    o += `        return AnalyticsEventPayload("${e.name}", p)\n    }\n\n`;
  }
  o += `}\n\n`;
  o += `/** Canonical user properties. [SET_ONCE_KEYS] must be sent with setOnce. */\ndata class AnalyticsUserProperties(\n${userProps.map((p) => `    val ${p.param}: ${ktType(p)}? = null,`).join('\n')}\n) {\n`;
  o += `    fun toMap(): Map<String, Any> = buildMap {\n${userProps.map((p) => `        ${p.param}?.let { put("${p.name}", ${wire(p, 'it')}) }`).join('\n')}\n    }\n\n`;
  o += `    companion object {\n        val SET_ONCE_KEYS: Set<String> = setOf(${userProps.filter((p) => p.setOnce).map((p) => `"${p.name}"`).join(', ')})\n    }\n}\n`;
  return o;
}

// ---------------------------------------------------------------- write / check

const gens = { web: genTs, ios: genSwift, android: genKotlin };
let stale = 0;
for (const [key, path] of Object.entries(targets)) {
  if (only && only !== key) continue;
  const repoRoot = key === 'web' ? beRoot : key === 'ios' ? IOS_REPO : ANDROID_REPO;
  if (!existsSync(repoRoot)) { console.warn(`skip ${key}: ${repoRoot} not found`); continue; }
  const out = gens[key]();
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== out) { console.error(`stale: ${path}`); stale++; } else console.log(`ok: ${key}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, out);
    console.log(`wrote ${key}: ${path} (${events.length} events)`);
  }
}
if (stale) { console.error('Run `node analytics/codegen.mjs` and commit the result.'); process.exit(1); }
