#!/usr/bin/env node
/**
 * Refresh the bundled IANA TLD list used by the invite email validator.
 *
 *   node apps/web/scripts/refresh-email-tlds.mjs \
 *     [--ios ../FitCircle-iOS/FitCircle/Core/Validation/EmailTLDs.generated.swift] \
 *     [--android ../Fitcircle-Android/FitCircle/app/src/main/java/com/fitcircle/app/core/validation/EmailTlds.kt]
 *
 * Always rewrites apps/web/app/lib/validation/email-tlds.generated.ts; pass the
 * mobile paths to regenerate their copies in the same run (all three must ship
 * the same list so the platforms agree). New TLDs are rare — refresh a couple
 * of times a year, or when someone reports a real address being rejected with
 * reason `unknown_tld`.
 *
 * Source: https://data.iana.org/TLD/tlds-alpha-by-domain.txt
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const here = path.dirname(fileURLToPath(import.meta.url));
const tsOut = path.resolve(here, '../app/lib/validation/email-tlds.generated.ts');

function arg(name) {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : null;
}

async function load() {
  const local = arg('--from');
  const text = local ? readFileSync(local, 'utf8') : await (await fetch(SOURCE)).text();
  const lines = text.split('\n').map((l) => l.trim());
  const version = (lines[0].match(/Version (\d+)/) ?? [])[1] ?? 'unknown';
  const tlds = lines.filter((l) => l && !l.startsWith('#')).map((l) => l.toLowerCase());
  if (tlds.length < 1000 || !tlds.includes('com')) throw new Error(`Suspicious TLD list (${tlds.length} entries)`);
  return { version, tlds: [...new Set(tlds)].sort() };
}

/** Wrap a space-separated list at ~100 columns. */
function chunks(tlds, width = 96) {
  const out = [];
  let line = '';
  for (const t of tlds) {
    if (line && line.length + t.length + 1 > width) {
      out.push(line);
      line = '';
    }
    line = line ? `${line} ${t}` : t;
  }
  if (line) out.push(line);
  return out;
}

const { version, tlds } = await load();
const lines = chunks(tlds);
const header = `Generated by apps/web/scripts/refresh-email-tlds.mjs from ${SOURCE}\n// IANA version ${version} (${tlds.length} TLDs). Do not edit by hand.`;

writeFileSync(
  tsOut,
  `// ${header}\n\nexport const IANA_TLD_VERSION = '${version}';\n\nexport const IANA_TLDS: ReadonlySet<string> = new Set(\n  [\n${lines
    .map((l) => `    '${l}',`)
    .join('\n')}\n  ]\n    .join(' ')\n    .split(' ')\n);\n`
);
console.log(`wrote ${tsOut}`);

const ios = arg('--ios');
if (ios) {
  writeFileSync(
    ios,
    `// ${header}\n// Mirror of FitCircleBE apps/web/app/lib/validation/email-tlds.generated.ts.\n\nenum EmailTLDs {\n    static let version = "${version}"\n\n    static let all: Set<String> = Set(\n        [\n${lines
      .map((l) => `            "${l}",`)
      .join('\n')}\n        ]\n        .joined(separator: " ")\n        .split(separator: " ")\n        .map(String.init)\n    )\n}\n`
  );
  console.log(`wrote ${ios}`);
}

const android = arg('--android');
if (android) {
  writeFileSync(
    android,
    `// ${header}\n// Mirror of FitCircleBE apps/web/app/lib/validation/email-tlds.generated.ts.\npackage com.fitcircle.app.core.validation\n\nobject EmailTlds {\n    const val VERSION = "${version}"\n\n    val ALL: Set<String> = listOf(\n${lines
      .map((l) => `        "${l}",`)
      .join('\n')}\n    ).joinToString(" ").split(" ").toHashSet()\n}\n`
  );
  console.log(`wrote ${android}`);
}
